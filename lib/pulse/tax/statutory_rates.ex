defmodule Pulse.Tax.StatutoryRates do
  @moduledoc """
  Значения законодательных параметров по умолчанию (раздел 5.5 ТЗ).

  **Внимание.** Налоговое законодательство Казахстана менялось с 2026
  года (новый Налоговый кодекс). Значения ниже — ориентир для работы
  системы, а **не проверенная истина**. Их нужно сверить с действующей
  редакцией и перепроверить с бухгалтером, после чего поправить через
  интерфейс: правка не требует релиза.

  Ставки хранятся в процентах, как в Налоговом кодексе. Суммы (МРП, МЗП)
  — в тенге.
  """

  @doc """
  Параметры на дату начала действия.

  Возвращает список карт для `Pulse.Tax.StatutoryRate`.
  """
  @spec defaults() :: [map()]
  def defaults do
    [
      rate("vat_rate", "Ставка НДС", "16", ~D[2026-01-01],
        note: "Значение из прототипа; требует сверки с действующей редакцией НК РК"
      ),
      rate("vat_rate_reduced", "Пониженная ставка НДС", "0", ~D[2026-01-01]),
      rate("mrp", "Месячный расчетный показатель", "4325", ~D[2026-01-01],
        note: "МРП на 2026 год — ориентир"
      ),
      rate("mzp", "Минимальная заработная плата", "85000", ~D[2026-01-01],
        note: "МЗП на 2026 год — ориентир"
      ),
      rate("opv", "Обязательные пенсионные взносы, %", "10", ~D[2026-01-01]),
      rate("opvr", "Обязательные пенсионные взносы работодателя, %", "1.5", ~D[2026-01-01]),
      rate("so", "Социальные отчисления, %", "3.5", ~D[2026-01-01]),
      rate(
        "vosms",
        "Взносы обязательного социального медицинского страхования, %",
        "2",
        ~D[2026-01-01]
      ),
      rate(
        "oosms",
        "Отчисления обязательного социального медицинского страхования, %",
        "3",
        ~D[2026-01-01]
      ),
      rate("ipn", "Индивидуальный подоходный налог, %", "10", ~D[2026-01-01]),
      rate("deduction_monthly", "Вычет по ИПН в месяц (МРП)", "30", ~D[2026-01-01]),
      rate("deduction_yearly", "Вычет по ИПН за год (МРП)", "360", ~D[2026-01-01]),
      # Верхние границы базы взносов и отчислений, в МЗП за месяц.
      rate("opv_cap_mzp", "Предел базы ОПВ (МЗП)", "50", ~D[2026-01-01]),
      rate("so_cap_mzp", "Предел базы СО (МЗП)", "7", ~D[2026-01-01]),
