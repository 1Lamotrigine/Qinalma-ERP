    ]
  end

  @doc """
  Коды, у которых значение задано в процентах.
  """
  @spec percent_codes() :: [String.t()]
  def percent_codes do
    ~w(vat_rate vat_rate_reduced opv opvr so vosms oosms ipn)
  end

  defp rate(code, name, value, valid_from, opts \\ []) do
    %{
      code: code,
      name: name,
      value: Decimal.new(value),
      valid_from: valid_from,
      valid_to: Keyword.get(opts, :valid_to),
      note: Keyword.get(opts, :note)
    }
  end
end
