  # Разделы, которые в MVP помечены «в разработке» (раздел 6 ТЗ).
  # Их пункты неактивны и ведут на серую пометку.
  @inactive_sections [:prod, :fa]

  @doc """
  Все разделы меню с вычисленными оттенками и типами пунктов.
  """
  @spec sections() :: [section()]
  def sections do
    @sections
    |> Enum.with_index()
    |> Enum.map(fn {section, index} ->
      inactive? = section.id in @inactive_sections

      section
      |> Map.put(:hue, rem(index * 47 + 80, 360))
      |> Map.put(:inactive, inactive?)
      |> Map.put(:groups, Enum.map(section.groups, &build_group(&1, inactive?)))
    end)
  end

  @doc """
  Раздел по идентификатору.
  """
  @spec get(atom()) :: section() | nil
  def get(id), do: Enum.find(sections(), &(&1.id == id))

  @doc """
  Идентификатор раздела, которому принадлежит пункт меню.
  """
  @spec section_id(String.t()) :: atom() | nil
  def section_id(item_title) do
    Enum.find_value(sections(), fn section ->
      if group_has_item?(section.groups, item_title), do: section.id
    end)
  end

  defp group_has_item?(groups, item_title) do
    Enum.any?(groups, fn group ->
      Enum.any?(group.items, &(&1.title == item_title))
    end)
  end

  @doc """
  Пункт меню по заголовку и разделу.
  """
  @spec find_item(atom(), String.t()) :: item() | nil
  def find_item(section_id, title) do
    with section when not is_nil(section) <- get(section_id),
         %{} = item <-
           Enum.find_value(section.groups, fn group ->
             Enum.find(group.items, &(&1.title == title))
           end) do
      item
    else
      _ -> nil
    end
  end

  @doc """
  Все пункты меню плоским списком: `{section, group_title, item}`.
  Используется глобальным поиском.
  """
  @spec all_items() :: [{section(), String.t(), item()}]
  def all_items do
    for section <- sections(),
        group <- section.groups,
        item <- group.items do
      {section, group.title, item}
    end
  end

  @doc """
  Поиск по названию пункта, раздела и группы. Возвращает до `limit` совпадений.
  """
  @spec search(String.t(), pos_integer()) :: [{section(), String.t(), item()}]
  def search(query, limit \\ 12) do
    query = String.downcase(String.trim(query))

    if query == "" do
      []
    else
      all_items()
      |> Enum.filter(fn {section, group, item} ->
        haystack =
          String.downcase("#{item.title} #{section.title} #{group}")

        String.contains?(haystack, query)
      end)
      |> Enum.take(limit)
    end
  end

  @doc """
  Тип пункта меню.
  """
  @spec kind(atom(), String.t()) :: kind()
  def kind(section_id, title) do
    case find_item(section_id, title) do
      %{kind: kind} -> kind
      nil -> :tool
    end
  end

  defp build_group({title, items}, inactive?) do
    %{
      title: title,
      items:
        Enum.map(items, fn
          {title, kind} ->
            %{title: title, kind: kind, primary: false, implemented: not inactive?}

          {title, kind, primary} ->
            %{title: title, kind: kind, primary: primary, implemented: not inactive?}
        end)
    }
  end
